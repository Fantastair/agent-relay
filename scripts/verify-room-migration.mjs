// Take a consistent read-only backup, then test migration on the copy only.
import {DatabaseSync,backup} from 'node:sqlite';
import {mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import {Store} from '../src/store.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const dir=path.join(root,'data-dev');await mkdir(dir,{recursive:true});
const destination=path.join(dir,`migration-${Date.now()}.sqlite`);
const source=new DatabaseSync(path.join(root,'data','relay.sqlite'),{readOnly:true});
await backup(source,destination);source.close();
const before=new DatabaseSync(destination,{readOnly:true});
const originalMessages=before.prepare('SELECT id,sender,text,reply_to,root_id,hop,native_key,meta,created_at FROM messages ORDER BY id').all();
const originalDeliveries=before.prepare('SELECT id,message_id,side,receipt,attempts,created_at FROM deliveries ORDER BY id').all();
const originalRoots=before.prepare('SELECT * FROM roots ORDER BY id').all(),originalSeen=before.prepare('SELECT * FROM seen ORDER BY side,session_id,native_key').all();
before.close();
let migrated=new Store(destination),roomId=migrated.activeRoomId();
assert.deepEqual(migrated.db.prepare('SELECT id,sender,text,reply_to,root_id,hop,native_key,meta,created_at FROM messages ORDER BY id').all(),originalMessages);
assert.deepEqual(migrated.db.prepare('SELECT id,message_id,side,receipt,attempts,created_at FROM deliveries ORDER BY id').all(),originalDeliveries);
assert.deepEqual(migrated.db.prepare('SELECT * FROM roots ORDER BY id').all(),originalRoots);
assert.deepEqual(migrated.db.prepare('SELECT * FROM seen ORDER BY side,session_id,native_key').all(),originalSeen);
assert.equal(migrated.db.prepare('SELECT count(*) AS n FROM messages WHERE room_id IS NULL').get().n,0);
assert.equal(migrated.db.prepare('SELECT count(*) AS n FROM deliveries WHERE room_id IS NULL').get().n,0);
const rooms=migrated.rooms().length;migrated.close();
migrated=new Store(destination);assert.equal(migrated.rooms().length,rooms);assert.equal(migrated.activeRoomId(),roomId);migrated.close();
const report={verifiedAt:new Date().toISOString(),sourceReadOnly:true,migratedCopy:destination,messages:originalMessages.length,deliveries:originalDeliveries.length,roots:originalRoots.length,seen:originalSeen.length,rooms,idempotent:true,messageChecksum:createHash('sha256').update(JSON.stringify(originalMessages)).digest('hex')};
await writeFile(path.join(dir,'migration-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
